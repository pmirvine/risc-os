#!/usr/bin/env node
// Generates tools/moreapps/!Letters/ThemePresets from Word's own theme
// files (Office Themes/Theme Colors and Theme Fonts), so the data is
// never typed by hand.
//
//   node tools/theme-presets.mjs [folder] [--check]
//     folder   the "Office Themes" folder (default: the Mac install of
//              Microsoft Word)
//     --check  re-generate in memory; exit 1 if the committed module
//              differs, else 0 (nothing is written)
import {readFileSync, writeFileSync, readdirSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const DEFAULT_DIR = '/Applications/Microsoft Word.app/Contents/' +
  'Resources/Office Themes';
const OUT = join(dirname(fileURLToPath(import.meta.url)),
  'moreapps', '!Letters', 'ThemePresets');
const SLOTS = ['dk1', 'lt1', 'dk2', 'lt2', 'accent1', 'accent2',
  'accent3', 'accent4', 'accent5', 'accent6', 'hlink', 'folHlink'];
const OFFICE = 'Office 2013 - 2022';

const files = (dir) => readdirSync(dir).filter((f) =>
  f.endsWith('.xml')).sort().map((f) =>
  readFileSync(join(dir, f), 'utf8'));
const order = (a, b) => (b.name === OFFICE) - (a.name === OFFICE) ||
  (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

function colors(xml) {
  const name = /<a:clrScheme[^>]*\sname="([^"]*)"/.exec(xml)?.[1];
  const slots = {};
  const sys = [];
  for (const s of SLOTS) {
    const m = new RegExp(`<a:${s}>\\s*<a:(srgbClr|sysClr)\\s[^>]*?` +
      '(?:val|lastClr)="([0-9A-Fa-f]{6})"[^>]*/>').exec(xml);
    const sysM = new RegExp(`<a:${s}>\\s*<a:sysClr\\s[^>]*lastClr=` +
      '"([0-9A-Fa-f]{6})"').exec(xml);
    const v = sysM ? sysM[1] : (m && m[1] === 'srgbClr' ? m[2] : null);
    if (!name || !v) throw new Error(`bad colour file ${name}: ${s}`);
    slots[s] = v.toUpperCase();
    if (sysM) sys.push(s);
  }
  return {name, slots, sys};
}

function fonts(xml) {
  const name = /<a:fontScheme[^>]*\sname="([^"]*)"/.exec(xml)?.[1];
  const face = (w) => new RegExp(`<a:${w}>\\s*<a:latin\\s[^>]*` +
    'typeface="([^"]*)"').exec(xml)?.[1];
  const major = face('majorFont');
  const minor = face('minorFont');
  if (!name || !major || !minor) throw new Error('bad font file');
  return {name, major, minor};
}

// one entry as JSON, broken after commas so no line passes 72 columns
function wrap(text, indent) {
  const lines = [];
  let cur = indent;
  for (const tok of text.split(/(?<=,)/)) {
    if (cur.length + tok.length > 72 && cur.trim()) {
      lines.push(cur.trimEnd());
      cur = indent + '  ';
    }
    cur += tok;
  }
  lines.push(cur);
  return lines.join('\n');
}
const list = (a) => '[\n' + a.map((e) =>
  wrap(JSON.stringify(e), '  ')).join(',\n') + '\n]';

export function generate(dir = DEFAULT_DIR) {
  const cs = files(join(dir, 'Theme Colors')).map(colors).sort(order);
  const fp = files(join(dir, 'Theme Fonts')).map(fonts).sort(order);
  return '// ThemePresets - Word\'s 23 colour schemes and 25 font pairs.\n' +
    '// generated by tools/theme-presets.mjs from Word\'s Office\n' +
    '// Themes; do not edit.\n//\n' +
    '//   COLOR_SCHEMES  [{name, slots: {dk1..folHlink: \'RRGGBB\'},\n' +
    '//                    sys: slots Word gives as sysClr}]\n' +
    '//   FONT_PAIRS     [{name, major, minor}]\n' +
    '//   OFFICE_COLORS, OFFICE_FONTS  the Office defaults (Calibri\n' +
    '//                  Light / Calibri), as ThemeRead\'s defaults\n\n' +
    'export const COLOR_SCHEMES = ' + list(cs) +
    ';\n\nexport const FONT_PAIRS = ' + list(fp) +
    ';\n\nexport const OFFICE_COLORS = COLOR_SCHEMES.find((c) =>\n' +
    `  c.name === '${OFFICE}');\n` +
    'export const OFFICE_FONTS = FONT_PAIRS.find((f) =>\n' +
    '  f.major === \'Calibri Light\' && f.minor === \'Calibri\');\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const dir = args.find((a) => !a.startsWith('--'));
  const text = generate(dir);
  if (check) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (cur !== text) {
      console.error('ThemePresets is out of date');
      process.exit(1);
    }
    console.log('ThemePresets is up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
